"""
config.py
Centralized settings, loaded from .env via pydantic-settings.

Every other module in this backend imports `settings` from here
instead of reading os.environ directly or hardcoding any URL / key.
This is the single source of truth for config.
"""

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    # ---------- Server ----------
    app_host: str = "0.0.0.0"
    app_port: int = 8000
    app_env: str = "development"
    allowed_origins: str = "*"

    # ---------- Database ----------
    # Postgres connection string (from Neon, or any Postgres host) —
    # e.g. postgresql://user:password@host/dbname?sslmode=require
    # This is now REQUIRED — services/master_store.py no longer uses
    # a local SQLite file, since a local file gets wiped every time
    # the hosting platform's container restarts/redeploys/spins down.
    # A real Postgres database survives all of that, independently.
    database_url: str = ""

    # ---------- Google Sheet Sync (current primary data source) ----------
    # The real-time registration spreadsheet. GOOGLE_SHEET_URL is
    # pasted in .env — the normal Google Sheets URL you get from the
    # browser address bar (share access must be "Anyone with the
    # link: Viewer"). Nothing here is ever hardcoded in the code.
    google_sheet_url: str = ""
    sheet_sync_interval_minutes: int = 1
    sheet_sync_enabled: bool = True

    # ---------- Legacy: Organization REST API (kept, OFF by default) ----------
    # Original design before we confirmed the real source of truth is
    # a Google Sheet, not a REST API. Code for this is untouched and
    # still here (services/org_api_client.py) in case IEML exposes a
    # real org API later — just flip USE_LEGACY_ORG_API to true.
    use_legacy_org_api: bool = False
    demo_mode: bool = True
    org_api_base_url: str = ""
    org_api_key: str = ""
    org_api_timeout_seconds: float = 8.0

    # ---------- External Portal Push Sync (NEW) ----------
    # Counterpart to Google Sheet Sync above, but PUSH instead of
    # PULL: the IEML registration portal calls
    # POST /api/external/save-data on THIS backend with new/updated
    # registrations (see routers/external.py + services/external_sync.py),
    # instead of us polling a sheet. This key is generated by us and
    # handed to the portal team to put in their `apiKey` header — it
    # is NOT the same as ORG_API_KEY above, which is for calling out
    # to someone else's API. Runs alongside Google Sheet Sync, not a
    # replacement for it — both write into the same visitors table.
    external_api_key: str = ""

    # ---------- Mailchimp Transactional / Mandrill Email (Mart Days confirmation) ----------
    # MAILCHIMP_TRANSACTIONAL_API_KEY comes from a Mailchimp TRANSACTIONAL
    # account (mandrillapp.com), NOT the regular Mailchimp Marketing login
    # used for audience/campaign emails -- those are two separate products
    # with separate billing, even under the same Mailchimp company account.
    # Left blank by default so a backend that hasn't set this up yet just
    # skips sending (logs a warning, never crashes) instead of failing
    # registration.
    mailchimp_transactional_api_key: str = ""
    # Must be a sender EMAIL on a domain verified (SPF/DKIM) in the
    # Mailchimp Transactional account before it can send.
    mailchimp_sender_email: str = ""
    mailchimp_sender_name: str = "IEML Sourcing Mart Days"

    # ---------- Gmail SMTP (Mart Days confirmation -- REPLACES Mailchimp) ----------
    # Switched to this because Mailchimp Transactional needed its own paid
    # activation separate from the regular Mailchimp Marketing plan, which
    # wasn't set up. Sends via smtp.gmail.com using an APP PASSWORD, not
    # the normal Gmail login password -- generate one at
    # https://myaccount.google.com/apppasswords (requires 2-Step
    # Verification to be turned on for the Gmail account first). Left
    # blank by default so a backend that hasn't set this up yet just
    # skips sending (logs a warning) instead of failing registration.
    gmail_sender_email: str = ""
    gmail_app_password: str = ""
    gmail_sender_name: str = "IEML Sourcing Mart Days"

    # ---------- Event Info ----------
    # Reused across every IEML event — this is the one thing that
    # changes between events, everything else stays generic.
    event_name: str = "Event"

    # ---------- Admin Auth (counter operators) ----------
    # Every counter operator must log in with these before they can
    # search/register/print. Password is stored as a bcrypt HASH,
    # never plaintext — generate one with generate_password_hash.py.
    admin_username: str = "admin"
    admin_password_hash: str = ""
    jwt_secret: str = ""
    jwt_expiry_hours: int = 12

    # ---------- Master Auth (master console — you + your manager) ----------
    # Completely separate credentials from ADMIN_USERNAME above.
    # Logging in with these (via master-login.html) issues a JWT with
    # role="master" instead of role="operator" — that's what unlocks
    # the master console's add/edit/delete + stats endpoints.
    # Generate the hash the exact same way as ADMIN_PASSWORD_HASH,
    # using generate_password_hash.py.
    master_username: str = ""
    master_password_hash: str = ""

    # ---------- Scanner Auth (entrance-scanning app — gate staff) ----------
    # Completely separate credentials from ADMIN_USERNAME and
    # MASTER_USERNAME above. Logging in with these (via the new
    # frontend-scan app) issues a JWT with role="scanner" — a
    # distinct role from "operator" and "master", so gate staff get
    # their own login without touching registration/printing or the
    # master console. Generate the hash the exact same way as the
    # other password hashes, using generate_password_hash.py.
    scanner_username: str = ""
    scanner_password_hash: str = ""

    # ---------- Mart Days counter gate (frontend/ only) ----------
    # DEPRECATED — replaced by ADMIN_MARTDAYS_USERNAME below (separate
    # login instead of an in-app second password). Field kept here,
    # unused, purely so an existing .env with this key set doesn't
    # need to be touched during rollout; safe to delete later.
    mart_days_gate_password: str = ""

    # ---------- Mart Days Operator Auth (badge desk — separate login) ----------
    # NEW. A SEPARATE operator account for the badge desk (frontend/
    # only), permanently scoped to Mart Days — completely independent
    # credentials from ADMIN_USERNAME above, generated the same way
    # (generate_password_hash.py). Logging in with these issues a
    # role="operator" token exactly like the regular admin login, but
    # with an extra event="mart_days" claim baked into the JWT itself
    # — so this operator's badge desk opens straight into Mart Days
    # mode, no separate in-app gate/password step needed, and the
    # backend trusts the TOKEN (not a query param) for which table an
    # operator's search/register/print calls should touch. Left blank
    # by default, so until this is configured the Mart Days operator
    # login simply doesn't exist yet (fails safe, same convention as
    # every other credential pair in this file).
    admin_martdays_username: str = ""
    admin_martdays_password_hash: str = ""

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        case_sensitive=False,
    )

    @property
    def allowed_origins_list(self) -> list[str]:
        """Split the comma-separated ALLOWED_ORIGINS into a list for CORS middleware."""
        if self.allowed_origins.strip() == "*":
            return ["*"]
        return [origin.strip() for origin in self.allowed_origins.split(",") if origin.strip()]

    @property
    def google_sheet_csv_url(self) -> str:
        """
        Converts a normal Google Sheet URL (the one you copy from the
        browser, e.g. .../spreadsheets/d/XXXX/edit#gid=0) into its
        CSV export link, so the backend can fetch it with a plain
        HTTP GET — no Google API key or service account needed, as
        long as the sheet is shared as "Anyone with the link: Viewer".
        Returns "" if GOOGLE_SHEET_URL isn't set yet.
        """
        url = self.google_sheet_url.strip()
        if not url or "/spreadsheets/d/" not in url:
            return ""

        sheet_id = url.split("/spreadsheets/d/")[1].split("/")[0]

        gid = "0"
        if "gid=" in url:
            gid = url.split("gid=")[1].split("&")[0].split("#")[0]

        return f"https://docs.google.com/spreadsheets/d/{sheet_id}/export?format=csv&gid={gid}"


# Import this single instance everywhere: `from config import settings`
settings = Settings()