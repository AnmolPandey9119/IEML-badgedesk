"""
services/external_sync.py
Receives registration records PUSHED from the IEML portal (via
routers/external.py's POST /api/external/save-data) and upserts them
into the master store — the push counterpart to services/sheet_sync.py's
pull-based sync. Both write into the exact same visitors table, so
print / scan / export / master-console code never needs to know or
care which source a given visitor came from.

--------------------------------------------------------------------
WHY THERE'S NO "ASSIGN A NEW URN" STEP HERE (unlike sheet_sync.py)
--------------------------------------------------------------------
sheet_sync.py has to invent a URN for every new sheet row, because a
spreadsheet row has no built-in unique ID of its own.

The portal is different: RegID IS already a unique registration
number, generated by the portal itself. So RegID becomes this
system's URN directly — same value, printed on the badge and encoded
in the QR. That also makes "is this new or already known" trivial:
just check whether that URN already exists.
"""

import logging

from services import master_store

logger = logging.getLogger("external_sync")

# Portal field name -> our core master_store column (see _CORE_FIELDS
# in master_store.py). This is a straight 1:1 rename, same spirit as
# sheet_sync.py's _HEADER_ALIASES — no value is changed, only which
# dict key it's filed under, and ONLY where an equivalent core column
# already exists (org/city/email/mobile). Anything from the portal
# NOT listed here still gets kept — under its own EXACT original
# field name, EXACT original value — in extra_json, so every one of
# the reference payload's fields reaches storage, nothing dropped and
# nothing invented.
_CORE_MAP = {
    "CompanyName": "org",
    "City": "city",
    "Email": "email",
    "Mobile_number": "mobile",
}

# Fields consumed explicitly below (by name-combining or renaming)
# rather than via _CORE_MAP — excluded from the generic "keep
# everything else in extra_json" loop so they don't end up stored
# twice under two different keys.
_HANDLED = {"RegID", "FirstName", "LastName", "Jobtitle", "RegistrationType", *_CORE_MAP.keys()}


def _map_record(record: dict) -> dict:
    """
    Converts one portal record (already-validated
    ExternalRegistrationRecord.model_dump()) into the dict shape
    master_store.insert_visitor/sync_update_visitor expect.

    Deliberately does the SAME two structural renames sheet_sync.py's
    _HEADER_ALIASES already does for the spreadsheet — nothing more:
      - FirstName + LastName combined into "name": there is only one
        printed name field on the badge / in the visitors table, so
        this combination is unavoidable, not a judgment call.
      - Jobtitle -> "designation": sheet_sync.py's own _HEADER_ALIASES
        already renames a "Designation" column this exact same way,
        because that's the field name the edit form / badge already
        read from — same rule applied here for consistency.
      - RegistrationType -> "category": stored EXACTLY as sent, no
        case change, matching sheet_sync's own "typeofbuyer": "category"
        alias (which also just copies the value as-is).
    Every other field (Title, Country_Code, Country, Address, State,
    PinCode, Website, SubmittedAt, BadgeDownloadStatus, EventName)
    is kept verbatim — original key, original value, untouched.
    """
    first = (record.get("FirstName") or "").strip()
    last = (record.get("LastName") or "").strip()
    name = f"{first} {last}".strip() or record.get("Email") or record.get("Mobile_number") or "Unnamed Visitor"

    mapped: dict = {"name": name}

    for portal_key, core_key in _CORE_MAP.items():
        value = record.get(portal_key)
        if value not in (None, ""):
            mapped[core_key] = value

    if record.get("Jobtitle"):
        mapped["designation"] = record["Jobtitle"]

    reg_type = (record.get("RegistrationType") or "").strip()
    if reg_type:
        mapped["category"] = reg_type

    # Every remaining field the portal sent — Title, Country_Code,
    # Country, Address, State, PinCode, Website, SubmittedAt,
    # BadgeDownloadStatus, EventName, and any future column — kept
    # verbatim under its EXACT original key/value. None of these are
    # reinterpreted into an existing core column (e.g. BadgeDownloadStatus
    # is NOT folded into "status" — that column already means something
    # else, populated from the sheet's own "Status" column, and
    # conflating the two would change what "status" means for
    # existing sheet-synced visitors).
    for key, value in record.items():
        if key not in _HANDLED and value not in (None, ""):
            mapped[key] = value

    return mapped


def run_sync(records: list[dict]) -> dict:
    """
    For each record: upsert by RegID (== URN). No hash-skip
    optimization like sheet_sync.py's — pushes are already
    event-driven (only sent when something happened on the portal
    side), not a full-sheet re-scan every minute, so every push is
    just applied directly. Never raises on a single bad record —
    one missing RegID is skipped and counted, the rest of the batch
    still goes through.
    """
    created = 0
    updated = 0
    skipped_invalid = 0

    for record in records:
        urn = str(record.get("RegID") or "").strip()
        if not urn:
            skipped_invalid += 1
            logger.warning("External sync: record with no RegID, skipped: %r", record)
            continue

        mapped = _map_record(record)

        if master_store.get_by_urn(urn):
            master_store.sync_update_visitor(urn, mapped, source_hash=None)
            updated += 1
        else:
            master_store.insert_visitor(urn, mapped, source="portal", source_hash=None, sheet_row=None)
            created += 1

    logger.info(
        "External sync done: %d created, %d updated, %d skipped_invalid (received %d)",
        created, updated, skipped_invalid, len(records),
    )
    return {
        "received": len(records),
        "created": created,
        "updated": updated,
        "skipped_invalid": skipped_invalid,
    }